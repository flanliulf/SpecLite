#!/usr/bin/env node

import { readFile, readdir, stat } from "node:fs/promises";
import path from "node:path";
import process from "node:process";

const root = path.resolve(process.cwd());
const docsRoot = path.join(root, "docs");
const entrypoint = path.join(docsRoot, "index.md");
const rootReadme = path.join(root, "README.md");
const packageJson = JSON.parse(await readFile(path.join(root, "package.json"), "utf8"));
const draftMarker = "> Status: Draft（草稿）";
const frozenMarker = "Status: Frozen Compatibility（冻结兼容）";
const movedMarker = "> Status: Moved（已迁移）";
const generatedFooterPrefix = "> Generated by（生成说明）：";
const relatedHeading = "## Related Documents（相关文档）";
const maxSecondLevelHeadings = 12;
const maxTableCellLength = 320;
const headingCountExemptions = new Set(["docs/quick-start.md", "docs/README.md", "docs/_STYLE_GUIDE.md"]);
const errors = [];

const markdownFiles = (await walk(docsRoot)).filter((filePath) => filePath.endsWith(".md")).sort();
const markdownSet = new Set(markdownFiles);
const contentByFile = new Map(
  await Promise.all(
    [...markdownFiles, rootReadme].map(async (filePath) => [filePath, await readFile(filePath, "utf8")]),
  ),
);
const draftFiles = new Set(markdownFiles.filter((filePath) => hasHeadMarker(filePath, draftMarker)));
const movedFiles = new Set(markdownFiles.filter((filePath) => hasHeadMarker(filePath, movedMarker)));
const frozenFiles = new Set(
  markdownFiles.filter((filePath) => filePath.startsWith(`${path.join(docsRoot, "glossary")}${path.sep}`)),
);
const compatibilityFiles = new Set([...movedFiles, ...frozenFiles]);
const linksByFile = new Map();

for (const filePath of [...markdownFiles, rootReadme]) {
  const links = extractMarkdownLinks(contentByFile.get(filePath) ?? "");
  const resolvedLinks = [];

  for (const link of links) {
    const resolved = await validateLink(filePath, link);
    if (resolved !== undefined) {
      resolvedLinks.push(resolved);
    }
  }

  linksByFile.set(filePath, resolvedLinks);
}

validateDraftIndexes();
validateCompatibilityEntries();
validatePackageBoundary(path.join(docsRoot, "quick-start.md"));
validatePackageBoundary(rootReadme);
validateRelatedDocuments();
validateNearestIndexes();
validateStyleRules();
validateReachability();

if (errors.length > 0) {
  console.error(`docs:check failed with ${errors.length} issue(s):`);
  for (const error of errors) {
    console.error(`- ${error}`);
  }
  process.exitCode = 1;
} else {
  console.log(
    `docs:check passed: ${markdownFiles.length} Markdown files, ${draftFiles.size} drafts, ${movedFiles.size} moved entries, links, style and governance rules valid.`,
  );
}

async function walk(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];

  for (const entry of entries) {
    if (entry.name === ".DS_Store") {
      continue;
    }
    const entryPath = path.join(directory, entry.name);
    if (entry.isDirectory()) {
      files.push(...(await walk(entryPath)));
    } else if (entry.isFile()) {
      files.push(entryPath);
    }
  }

  return files;
}

function hasHeadMarker(filePath, marker) {
  return (contentByFile.get(filePath) ?? "")
    .split("\n")
    .slice(0, 8)
    .some((line) => line.startsWith(marker));
}

function stripFences(markdown) {
  return markdown.replace(/^```[\s\S]*?^```\s*$/gm, "").replace(/^~~~[\s\S]*?^~~~\s*$/gm, "");
}

function extractMarkdownLinks(markdown) {
  const withoutFences = stripFences(markdown).replace(/`[^`\n]*`/g, "");
  const links = [];
  const pattern = /!?\[[^\]]*\]\((<[^>]+>|[^)\s]+)(?:\s+["'][^"']*["'])?\)/g;

  for (const match of withoutFences.matchAll(pattern)) {
    links.push(match[1].replace(/^<|>$/g, ""));
  }

  return links;
}

async function validateLink(sourceFile, rawTarget) {
  if (/^(?:https?:|mailto:|tel:|data:)/i.test(rawTarget)) {
    return undefined;
  }

  const [rawPath, fragment = ""] = rawTarget.split("#", 2);
  let decodedPath;
  let decodedFragment;
  try {
    decodedPath = decodeURIComponent(rawPath);
    decodedFragment = decodeURIComponent(fragment);
  } catch {
    errors.push(`${relative(sourceFile)} contains an invalid encoded link: ${rawTarget}`);
    return undefined;
  }

  const targetPath = decodedPath === "" ? sourceFile : path.resolve(path.dirname(sourceFile), decodedPath);
  if (!targetPath.startsWith(`${root}${path.sep}`) && targetPath !== root) {
    errors.push(`${relative(sourceFile)} links outside the repository: ${rawTarget}`);
    return undefined;
  }

  try {
    const targetStat = await stat(targetPath);
    if (targetStat.isDirectory()) {
      errors.push(`${relative(sourceFile)} links to a directory instead of an explicit entry: ${rawTarget}`);
      return undefined;
    }
  } catch {
    errors.push(`${relative(sourceFile)} has a missing target: ${rawTarget}`);
    return undefined;
  }

  if (decodedFragment !== "" && targetPath.endsWith(".md")) {
    const targetContent = contentByFile.get(targetPath) ?? (await readFile(targetPath, "utf8"));
    const anchors = markdownAnchors(targetContent);
    if (!anchors.has(decodedFragment.toLowerCase())) {
      errors.push(`${relative(sourceFile)} has a missing fragment: ${rawTarget}`);
    }
  }

  return targetPath;
}

function markdownAnchors(markdown) {
  const anchors = new Set();
  const counts = new Map();

  for (const match of markdown.matchAll(/^#{1,6}\s+(.+?)\s*#*$/gm)) {
    const base = githubSlug(match[1]);
    const count = counts.get(base) ?? 0;
    counts.set(base, count + 1);
    anchors.add(count === 0 ? base : `${base}-${count}`);
  }

  return anchors;
}

function githubSlug(heading) {
  return heading
    .toLowerCase()
    .replace(/<[^>]*>/g, "")
    .replace(/[^\p{L}\p{N}\s_-]/gu, "")
    .trim()
    .replace(/\s+/g, "-");
}

function validateDraftIndexes() {
  const indexFiles = markdownFiles.filter((filePath) => path.basename(filePath) === "index.md");
  for (const indexFile of indexFiles) {
    for (const target of linksByFile.get(indexFile) ?? []) {
      if (draftFiles.has(target)) {
        errors.push(`${relative(indexFile)} publishes draft page ${relative(target)}`);
      }
    }
  }
}

function validateCompatibilityEntries() {
  for (const filePath of compatibilityFiles) {
    const content = contentByFile.get(filePath) ?? "";
    const kind = frozenFiles.has(filePath) ? "Frozen Compatibility" : "Moved";
    if (frozenFiles.has(filePath) && !content.includes(frozenMarker)) {
      errors.push(`${relative(filePath)} is missing the Frozen Compatibility marker`);
    }
    const replacement = (linksByFile.get(filePath) ?? []).find(
      (target) => markdownSet.has(target) && !compatibilityFiles.has(target) && !draftFiles.has(target),
    );
    if (replacement === undefined) {
      errors.push(`${relative(filePath)} does not link to a primary public replacement`);
    }
    if (/^## /m.test(stripFences(content))) {
      errors.push(`${relative(filePath)} is a ${kind} entry but carries its own sections; keep only redirect links`);
    }
  }
}

function validatePackageBoundary(sourceFile) {
  const packageFiles = packageJson.files ?? [];

  for (const target of linksByFile.get(sourceFile) ?? []) {
    const targetRelative = relative(target);
    if (target === sourceFile || packageFiles.some((entry) => packageEntryContains(entry, targetRelative))) {
      continue;
    }
    errors.push(`${relative(sourceFile)} links to file outside package.json.files: ${targetRelative}`);
  }
}

function packageEntryContains(entry, targetRelative) {
  const normalized = entry.replace(/\\/g, "/");
  return normalized.endsWith("/") ? targetRelative.startsWith(normalized) : targetRelative === normalized;
}

function isRelatedExempt(filePath) {
  const relativePath = relative(filePath);
  return (
    path.basename(filePath) === "index.md" ||
    relativePath === "docs/README.md" ||
    relativePath === "docs/_STYLE_GUIDE.md" ||
    relativePath === "docs/quick-start.md" ||
    compatibilityFiles.has(filePath) ||
    draftFiles.has(filePath)
  );
}

function validateRelatedDocuments() {
  for (const filePath of markdownFiles) {
    const relativePath = relative(filePath);
    if (isRelatedExempt(filePath)) {
      continue;
    }
    const content = contentByFile.get(filePath) ?? "";
    if (!content.includes(relatedHeading)) {
      errors.push(`${relativePath} is missing ${relatedHeading}`);
      continue;
    }
    const relatedSection = content.slice(content.indexOf(relatedHeading) + relatedHeading.length);
    const relatedLinks = extractMarkdownLinks(relatedSection).filter(
      (target) => !/^(?:https?:|mailto:|tel:|data:)/i.test(target),
    );
    if (relatedLinks.length === 0) {
      errors.push(`${relativePath} has no local relationship link under ${relatedHeading}`);
    }
  }
}

function validateNearestIndexes() {
  const indexSet = new Set(markdownFiles.filter((filePath) => path.basename(filePath) === "index.md"));
  const maintainerDocs = new Set(["docs/README.md", "docs/_STYLE_GUIDE.md"]);

  for (const filePath of markdownFiles) {
    const relativePath = relative(filePath);
    if (
      indexSet.has(filePath) ||
      draftFiles.has(filePath) ||
      compatibilityFiles.has(filePath) ||
      maintainerDocs.has(relativePath)
    ) {
      continue;
    }
    let directory = path.dirname(filePath);
    let nearestIndex;
    while (directory.startsWith(docsRoot)) {
      const candidate = path.join(directory, "index.md");
      if (indexSet.has(candidate) && candidate !== filePath) {
        nearestIndex = candidate;
        break;
      }
      if (directory === docsRoot) {
        break;
      }
      directory = path.dirname(directory);
    }
    if (nearestIndex === undefined) {
      errors.push(`${relativePath} has no index.md in its directory or an ancestor directory`);
      continue;
    }
    if (!(linksByFile.get(nearestIndex) ?? []).includes(filePath)) {
      errors.push(`${relativePath} is not listed by its nearest index ${relative(nearestIndex)}`);
    }
  }
}

function validateStyleRules() {
  for (const filePath of markdownFiles) {
    const relativePath = relative(filePath);
    const content = contentByFile.get(filePath) ?? "";
    const lines = content.split("\n");
    let inFence = false;
    let secondLevelHeadings = 0;
    let sawStepSection = false;

    for (let index = 0; index < lines.length; index += 1) {
      const line = lines[index];
      const lineNumber = index + 1;
      if (/^(```|~~~)/.test(line)) {
        inFence = !inFence;
        continue;
      }
      if (inFence) {
        continue;
      }
      if (/^---\s*$/.test(line) || /^\*\*\*\s*$/.test(line) || /^___\s*$/.test(line)) {
        errors.push(`${relativePath}:${lineNumber} uses a horizontal rule`);
      }
      if (/^#{4,6}\s/.test(line)) {
        errors.push(`${relativePath}:${lineNumber} uses a level-4 or deeper heading`);
      }
      if (/^## /.test(line)) {
        if (/^## Step \d+/.test(line)) {
          if (!sawStepSection) {
            secondLevelHeadings += 1;
            sawStepSection = true;
          }
        } else {
          secondLevelHeadings += 1;
        }
      }
      if (/^:::/.test(line)) {
        errors.push(`${relativePath}:${lineNumber} uses Starlight admonition syntax`);
      }
      if (/\/Users\/|\/home\/[a-z]|[A-Z]:\\Users\\/.test(line)) {
        errors.push(`${relativePath}:${lineNumber} contains a machine-local absolute path`);
      }
      if (/^\*?本文(?:档)?由 .*Skill (?:自动)?生成/.test(line) && !line.startsWith(generatedFooterPrefix)) {
        errors.push(`${relativePath}:${lineNumber} generated-by footer must use the "${generatedFooterPrefix}" form`);
      }
      if (line.startsWith("|") && !/^\|\s*:?-+:?\s*(\|\s*:?-+:?\s*)*\|?\s*$/.test(line)) {
        const cells = line.split("|").slice(1, -1);
        for (const cell of cells) {
          if (cell.trim().length > maxTableCellLength) {
            errors.push(
              `${relativePath}:${lineNumber} has a table cell longer than ${maxTableCellLength} characters; move details into prose or the owning document`,
            );
            break;
          }
        }
      }
    }

    if (
      !headingCountExemptions.has(relativePath) &&
      !relativePath.startsWith("docs/reference/glossary/epics/") &&
      secondLevelHeadings > maxSecondLevelHeadings
    ) {
      errors.push(
        `${relativePath} has ${secondLevelHeadings} second-level headings; the style guide allows at most ${maxSecondLevelHeadings}`,
      );
    }
  }
}

function validateReachability() {
  const visited = new Set();
  const queue = [entrypoint];

  while (queue.length > 0) {
    const current = queue.shift();
    if (current === undefined || visited.has(current)) {
      continue;
    }
    visited.add(current);
    for (const target of linksByFile.get(current) ?? []) {
      if (markdownSet.has(target) && !visited.has(target)) {
        queue.push(target);
      }
    }
  }

  for (const filePath of markdownFiles) {
    if (!draftFiles.has(filePath) && !movedFiles.has(filePath) && !visited.has(filePath)) {
      errors.push(`${relative(filePath)} is not reachable from docs/index.md`);
    }
  }
}

function relative(filePath) {
  return path.relative(root, filePath).split(path.sep).join("/");
}
